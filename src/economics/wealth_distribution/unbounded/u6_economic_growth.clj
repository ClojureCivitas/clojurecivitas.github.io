;; ## Growth

;; Economic growth is the accumulation of useful knowledge.
;; Knowledge lets us transform resources into things that were previously impossible.
;; Growth expands what people can do.
;; It enables new solutions to old problems and creates opportunities that did not previously exist.

;; Growth is good because progress is good.
;; There is no known limit to useful knowledge,
;; or how much better life can become.
;; There is no inherent reason to stop growing.

;; But economic growth is often used to justify actions that undermine progress.
;; Destruction to generate economic activity.
;; Exploitation to increase output.
;; Investment that concentrates wealth.
;; A narrow definition of growth conceals a decline in human opportunity.

;; Economic progress requires a system where many people participate in creating and benefiting from new wealth.

;; ## Circulation

;; Money coordinates the economy.
;; Circulation connects resources with unmet needs.
;; Each exchange puts people, skills, and capital to productive use.
;; Exchanges also create income, experience, and knowledge.
;; Those in turn encourage investment, innovation, and higher productivity.

;; Circulation encourages ideas, skills, and opportunities.
;; The result is economic growth: *more knowledge, greater productivity, and more resources available to improve human life.*

;; ## Participation

;; Growth depends on how many people can participate in creating and using resources.
;; An economy where more people participate will discover and develop more opportunities.

;; For much of history, wealth and power have been highly concentrated.
;; Under feudalism, most people owned little or no productive capital.
;; They worked land controlled by nobles and received enough to survive,
;; without the opportunity to accumulate wealth of their own.

;; The people who owned the land decided what was produced, who could use resources, and who benefited from them.
;; Most people were bound to the land and had little control over their work, resources, or future.
;; Economic activity was organized around obligation and hierarchy.

;; When people cannot own, invest, or experiment,
;; they have little incentive to improve the system.
;; Innovation is slow because fewer people are able to try new ideas.
;; Prosperity depends less on who owns today's wealth than on who has the opportunity to create tomorrow's wealth.

;; > "The best way to predict the future is to invent it." -- Alan Kay

;; Broad participation is a prerequisite for long-run prosperity.
;; Markets thrive when many people can own, invest, and create.
;; As ownership becomes more concentrated, participation degrades to obligation.
;; The system takes on feudalistic qualities.

;; ## Error Correction

;; Progress depends on finding and correcting errors.
;; In science, bad explanations are replaced with better ones.
;; In economics, harmful feedback loops must also be corrected.
;; Wealth concentration is one such feedback loop.
;; As wealth accumulates, it generates more income, influence, and opportunities to accumulate even more wealth.
;; Left unchecked, this reduces competition and participation over time.

;; *How do we ensure that the next generation can create wealth too?*

;; A wealth tax is an error-correction mechanism.
;; It helps preserve the conditions for broad participation, productive competition, and continued economic progress.

