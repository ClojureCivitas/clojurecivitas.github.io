;; ## Storytime

;; My brother's friend had a newspaper delivery route.
;; When he was busy, he paid my brother to deliver the papers.
;; My brother then paid me to help him.
;; I remember thinking *this is amazing!*
;; Somehow, everyone benefited.
;; The newspapers got delivered, my brother made money, and I made money too.
;; *Economies can grow when people coordinate and multiply their efforts.*

;; My grade 4 teacher had a gold star system.
;; If you were well behaved, you earned a star.
;; You could spend a star to take a 15-minute break in the library.
;; I quickly discovered the optimal strategy: *don't spend them.*
;; I saved every star I earned.
;; By the end of the year, I had enough for an entire day off.
;; I proudly asked to cash them all in together.
;; My teacher, somewhat startled, said no.
;; The reward system created an incentive I don't think my teacher intended.

;; I have personally been on the "creative destruction" side.
;; I've built systems that automated work people used to do manually.
;; One example was automating ship loading/unloading operations at ports.
;; The technology we produced made the process safer, faster, and more efficient.
;; *But it also meant fewer jobs.*

;; ![Driverless straddle carriers deliver containers for ship loading](autostrad.jpg){#fig-autostrad}

;; This is creative destruction.
;; It is how progress happens.
;; I don't think the answer is to stop innovation.
;; The world is better because we build better tools.
;; But it raises an important question:
;; *Who captures the gains from that progress?*

;; A problem arises when wealth accumulates faster than it circulates.
;; When ordinary people cannot afford to consume, *where are the customers?*
;; Growth requires both innovation and demand.
;; We need people creating new things, and people with enough purchasing power to participate in the economy.
;; Circulation determines whether everyone can participate.

;; `income → spending → demand → businesses → jobs → income`

;; Systems produce behaviors.
;; Economies grow through networks of participation.
;; Progress comes from building better tools.
;; :::

;; ## Conclusion

;; A broad definition of growth must include distribution.
;; Economic growth depends on participation.
;; Businesses need customers.
;; Customers need purchasing power.
;; Purchasing power depends on broad opportunity.
;; Opportunity depends on wealth continuing to circulate.
;; Wealth is the result of past success.
;; Participation creates future success.
;; Healthy economies need both.

